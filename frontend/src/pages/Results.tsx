import { Link, useLocation } from "react-router-dom";
import { Button } from "@/components/ui/button";
import { Card, CardContent, CardHeader, CardTitle } from "@/components/ui/card";
import { ArrowLeft } from "lucide-react";

interface PredictionResult {
  crop: string;
  prediction: number;
  unit: string;
  model_version: string;
  target: string;
  features_used: string[];
}

const Results = () => {
  const location = useLocation();
  const formData = location.state?.formData;
  const predictionResult = location.state?.predictionResult as PredictionResult | undefined;

  if (!formData || !predictionResult) {
    return (
      <div className="max-w-4xl mx-auto px-4 sm:px-6 lg:px-8 py-12 text-center">
        <h1 className="text-2xl font-bold mb-4">No Prediction Result Found</h1>
        <p className="text-muted-foreground mb-8">Please submit the prediction form first.</p>
        <Link to="/predict">
          <Button>Go to Prediction Form</Button>
        </Link>
      </div>
    );
  }

  return (
    <div className="max-w-5xl mx-auto px-4 sm:px-6 lg:px-8 py-12 space-y-8">
      <div>
        <Link to="/predict" className="inline-flex items-center text-muted-foreground hover:text-foreground mb-4">
          <ArrowLeft className="w-4 h-4 mr-2" />
          Back to Form
        </Link>
        <h1 className="text-4xl font-bold mb-2">Prediction Result</h1>
        <p className="text-muted-foreground">
          Deterministic estimate for {predictionResult.crop} using {predictionResult.model_version}
        </p>
      </div>

      <Card className="shadow-card">
        <CardHeader>
          <CardTitle>Estimated Yield</CardTitle>
        </CardHeader>
        <CardContent className="space-y-3">
          <p className="text-4xl font-bold">{predictionResult.prediction.toFixed(2)} {predictionResult.unit}</p>
          <p className="text-sm text-muted-foreground">Target: {predictionResult.target}</p>
          <p className="text-sm text-muted-foreground">
            This result is generated by the trained model pipeline and is distinct from optional advisory chat output.
          </p>
        </CardContent>
      </Card>

      <Card className="shadow-card">
        <CardHeader>
          <CardTitle>Input Summary</CardTitle>
        </CardHeader>
        <CardContent>
          <div className="grid grid-cols-1 md:grid-cols-2 gap-4 text-sm">
            <p><strong>Crop:</strong> {formData.crop}</p>
            <p><strong>Region:</strong> {formData.district}, {formData.state}</p>
            <p><strong>Year:</strong> {formData.year}</p>
            <p><strong>Rainfall (mm):</strong> {formData.rainfall_mm}</p>
            <p><strong>Avg Temperature (°C):</strong> {formData.avg_temperature_c}</p>
            <p><strong>Soil Type:</strong> {formData.soil_type}</p>
            <p><strong>Fertilizer (kg/acre):</strong> {formData.fertilizer_used_kg_per_acre}</p>
            <p><strong>Pesticide (lit/acre):</strong> {formData.pesticide_used_lit_per_acre}</p>
          </div>
        </CardContent>
      </Card>

      <div className="flex justify-center">
        <Link to="/predict">
          <Button size="lg">Run Another Prediction</Button>
        </Link>
      </div>
    </div>
  );
};

export default Results;
